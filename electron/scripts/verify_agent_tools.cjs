const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { app } = require('electron');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'catnip-tools-'));
app.setPath('userData', path.join(root, 'user-data'));
process.env.CATNIP_PROJECTS_ROOT = path.join(root, 'projects');
process.env.CATNIP_PROJECT_SESSIONS_ROOT = path.join(root, 'sessions');
const secret = 'fixture-model-token-no-credentials';
async function main() {
  await app.whenReady();
  const { ToolRegistry } = require('../dist/main/agent-tools/registry.js');
  const { createToolRegistry } = require('../dist/main/agent-tools/index.js');
  const { boardTool } = require('../dist/main/agent-tools/boards.js');
  const { RuntimeTools } = require('../dist/main/agent-tools/mcp.js');
  const { createProject, getActiveProject } = require('../dist/main/project-session.js');
  const { buildRigInitConfig } = require('../dist/main/agent.js');
  createProject('project-a');
  const project = getActiveProject();
  const abort = new AbortController();
  const context = { profile: 'default', projectId: project.id, projectDir: project.projectDir, conversationId: 'conversation-fixture', signal: abort.signal };
  const registry = createToolRegistry(context, [secret]);
  const execute = (name, input) => registry.execute(name, input);
  const success = async (name, input) => { const result = await execute(name, input); assert.equal(result.isError, false, result.content); return result; };
  const refused = async (name, input, code) => { const result = await execute(name, input); assert.equal(result.isError, true, `${name} ${JSON.stringify(input)}: ${result.content}`); if (code) assert.match(result.content, code); return result; };
  await success('Write', { path: 'main/fixture.c', content: 'alpha\nbeta\n' });
  let read = JSON.parse((await success('Read', { path: 'main/fixture.c', offset: 2, limit: 1 })).content);
  assert.match(read.content, /2: beta/); assert.match(read.contentSha256, /^[a-f0-9]{64}$/);
  await refused('Write', { path: 'main/fixture.c', content: 'overwrite' }, /MATCHING_CONTENT_SHA256/);
  await success('Write', { path: 'main/fixture.c', content: 'gamma\nbeta\n', expectedContentSha256: read.contentSha256 });
  await refused('Write', { path: 'main/fixture.c', content: 'stale overwrite', expectedContentSha256: read.contentSha256 }, /MATCHING_CONTENT_SHA256/);
  await success('Edit', { path: 'main/fixture.c', oldText: 'gamma', newText: 'alpha' });
  await refused('Edit', { path: 'main/fixture.c', oldText: 'not present', newText: 'bad' }, /UNIQUE/);
  await success('Write', { path: 'duplicate.c', content: 'repeat repeat' });
  await refused('Edit', { path: 'duplicate.c', oldText: 'repeat', newText: 'bad' }, /UNIQUE/);
  await refused('Read', { path: 'main/fixture.c', offset: 0 }, /ARGUMENTS/);
  await refused('Read', { path: 'main/fixture.c', extra: true }, /ARGUMENTS/);
  await refused('Unknown', {}, /PROFILE_FORBIDDEN/);
  for (const file of ['../escape.c', path.join(root, 'outside.c'), '.catnip/state.json', '.env', 'wifi_secrets.h', 'credentials.json', 'build/main.c', 'main.c:stream']) {
    await refused('Write', { path: file, content: 'bad' });
  }
  fs.writeFileSync(path.join(project.projectDir, 'binary.bin'), Buffer.from([0, 1, 2]));
  fs.writeFileSync(path.join(project.projectDir, 'large.c'), 'x'.repeat(150000));
  await refused('Read', { path: 'binary.bin' }, /BINARY/); await refused('Read', { path: 'large.c' }, /TOO_LARGE/);
  fs.mkdirSync(path.join(root, 'outside')); fs.writeFileSync(path.join(root, 'outside', 'data.c'), 'outside-secret');
  fs.symlinkSync(path.join(root, 'outside'), path.join(project.projectDir, 'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  await refused('Read', { path: 'linked/data.c' }, /LINK/);
  fs.linkSync(path.join(project.projectDir, 'main/fixture.c'), path.join(project.projectDir, 'hardlinked.c'));
  await refused('Read', { path: 'hardlinked.c' }, /LINK/);
  await success('Write', { path: 'bom.c', content: '\ufeffsource\r\n' });
  const bomRead = JSON.parse((await success('Read', { path: 'bom.c' })).content);
  await success('Write', { path: 'bom.c', content: '\ufeffupdated\r\n', expectedContentSha256: bomRead.contentSha256 });
  fs.unlinkSync(path.join(project.projectDir, 'hardlinked.c'));
  const listed = JSON.parse((await success('List', {})).content); assert(!listed.entries.some(e => e.name === '.catnip' || e.name === 'linked'));
  const found = JSON.parse((await success('Grep', { query: 'alpha' })).content); assert(found.matches.some(m => m.path.includes('fixture.c')));
  registry.register({ definition: { name: 'fixture-output', description: 'bounded result', parameters: { type: 'object' } }, profiles: ['default'], execute: async () => secret + 'x'.repeat(30000) });
  const bounded = await success('fixture-output', {}); assert(bounded.content.length < 24100); assert(!bounded.content.includes(secret)); assert.match(bounded.content, /truncated/);
  // No tool side effect can be allowed in analysis or plan even when the caller supplies it.
  for (const profile of ['explore_analysis', 'explore_plan']) {
    const restricted = createToolRegistry({ ...context, profile }, [], [{ definition: { name: 'fixture-side-effect', description: 'forbidden', parameters: { type: 'object' } }, profiles: ['default'], execute: async () => { throw new Error('SIDE_EFFECT_EXECUTED'); } }]);
    for (const name of ['Write', 'Edit', 'Read', 'BoardPack', 'fixture-side-effect', 'hardboard_idf_build', 'hardboard_idf_flash', 'hardboard_serial_read']) assert.equal((await restricted.execute(name, {})).isError, true);
  }
  const pack = JSON.parse((await success('BoardPack', { id: 'esp32-s3-generic' })).content); assert.equal(pack.display, null); assert.equal(pack.version, '1.0.0');
  await success('BoardPack', { id: pack.id, document: 'VALIDATION.md' }); await refused('BoardPack', { id: pack.id, document: '../escape.md' }, /NOT_DECLARED/);
  const ottoPack = JSON.parse((await success('BoardPack', { id: 'otto-robot-st7789' })).content);
  assert.equal(ottoPack.version, '1.0.0'); assert.equal(ottoPack.chip, 'esp32s3');
  assert.equal(ottoPack.display.controller, 'ST7789'); assert.equal(ottoPack.display.width, 240);
  assert.equal(ottoPack.display.height, 240); assert.equal(ottoPack.pins.lcd.cs, 12);
  assert.equal(ottoPack.validationStatus, 'REAL_DEVICE_DISPLAY_VALIDATED');
  await success('BoardPack', { id: ottoPack.id, document: 'README.md' });
  const hardwareDoc = await success('BoardPack', { id: ottoPack.id, document: 'HARDWARE.md' });
  assert.match(hardwareDoc.content, /MOSI \/ SDA.*10/);
  assert.match(hardwareDoc.content, /GPIO12.*right_hand_pin/);
  await refused('BoardPack', { id: ottoPack.id, document: '../esp32-s3-generic/manifest.json' }, /NOT_DECLARED/);
  const badRoot = path.join(root, 'packs'); fs.mkdirSync(path.join(badRoot, 'invalid'), { recursive: true });
  fs.writeFileSync(path.join(badRoot, 'invalid', 'manifest.json'), JSON.stringify({ schemaVersion: 1, id: 'invalid', version: 'latest', chip: 'esp32s3', documents: [] }));
  const bad = new ToolRegistry(context); bad.register(boardTool(badRoot)); assert.equal((await bad.execute('BoardPack', { id: 'invalid' })).isError, true);
  const runtime = new RuntimeTools();
  const calls = [];
  runtime.client = { callTool: async input => { calls.push(input); return { content: [{ type: 'text', text: JSON.stringify({ exitCode: 0 }) }] }; } };
  await runtime.call('hardboard.idf_build', {}, context); assert.equal(calls[0].arguments.projectDir, project.projectDir);
  await assert.rejects(runtime.call('hardboard.idf_flash', { projectDir: '../project-b', port: 'COM10' }, context), /CROSS_PROJECT/);
  await assert.rejects(runtime.call('attachment.read_text', { conversationId: 'other', attachmentId: 'att-x' }, context), /CROSS_CONVERSATION/);
  runtime.client = { callTool: async () => ({ content: [{ type: 'text', text: JSON.stringify({ exitCode: 1, stderr: 'compiler failed' }) }] }) };
  await assert.rejects(runtime.call('hardboard.idf_build', {}, context), /COMMAND_FAILED/);
  await assert.rejects(runtime.call('hardboard.idf_erase_flash', {}, context), /NOT_ALLOWED/);
  await assert.rejects(runtime.call('storage.save', { workspace: '../../outside', data: '{}' }, context), /WORKSPACE_NAME/);
  await assert.rejects(runtime.call('browser.workflow_save', { recordingFile: path.join(root, 'outside.json') }, context), /ARBITRARY_FILE/);
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aHioAAAAASUVORK5CYII=', 'base64');
  runtime.client = { callTool: async () => ({ content: [{ type: 'text', text: 'captured' }, { type: 'image', mimeType: 'image/png', data: png.toString('base64') }] }) };
  const capture = await runtime.call('browser.screenshot', {}, context);
  assert.equal(capture.images.length, 1); assert.deepEqual(fs.readFileSync(capture.images[0].path), png);
  assert(capture.images[0].path.startsWith(project.projectDir)); assert(!JSON.stringify(capture).includes(png.toString('base64')));
  runtime.client = { callTool: async () => ({ content: [{ type: 'resource_link' }] }) };
  await assert.rejects(runtime.call('browser.getState', {}, context), /UNSUPPORTED_CONTENT/);
  const cancellation = new AbortController();
  runtime.client = { callTool: async (_input, _schema, options) => { assert.equal(options.signal, cancellation.signal); cancellation.abort(); return { content: [] }; } };
  await assert.rejects(runtime.call('browser.getState', {}, { ...context, signal: cancellation.signal }));
  await refused('Write', { path: 'must-not-leak.c', content: secret }, /CREDENTIAL_ARGUMENT/);
  const quotedSecret = 'fixture-"quoted-host-secret';
  const quotedRegistry = new ToolRegistry(context, [quotedSecret]);
  quotedRegistry.register({ definition: { name: 'fixture-quoted', description: 'quoted fixture', parameters: { type: 'object' } }, profiles: ['default'], execute: async () => ({ text: quotedSecret }) });
  const quotedResult = await quotedRegistry.execute('fixture-quoted', {}); assert.equal(quotedResult.isError, false); assert(!quotedResult.content.includes('quoted-host-secret'));
  assert.equal((await quotedRegistry.execute('fixture-quoted', { secret: quotedSecret })).isError, true);
  runtime.client = null;
  const model = { upstreamModel: 'fixture', baseUrl: 'https://example.com/anthropic', authToken: secret, authField: 'ANTHROPIC_API_KEY', contextWindow: 131072, reserveTokens: 36864, maxOutputTokens: 32768, keepRecentTokens: 24000 };
  const first = buildRigInitConfig('default', model, registry.definitions(), { conversationId: 'same-name' });
  assert(first.sessionFile.startsWith(project.projectDir));
  createProject('project-b');
  const second = buildRigInitConfig('default', model, registry.definitions(), { conversationId: 'same-name' });
  assert.notEqual(first.sessionFile, second.sessionFile);
  assert.equal(buildRigInitConfig('explore_analysis', model, [], { conversationId: 'same-name' }).sessionFile, null);
  abort.abort(); await refused('List', {}, /ABORTED/);
  console.log('Agent Tools passed: read/write/edit, hash concurrency, bounds, private paths, links, schema, profiles, board versions, Runtime project/attachment/error boundaries, session isolation.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { app.quit(); fs.rmSync(root, { recursive: true, force: true }); });
