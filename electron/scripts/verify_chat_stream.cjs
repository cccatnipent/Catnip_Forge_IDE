const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { app } = require('electron');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'catnip-chat-stream-'));

async function main() {
  app.setPath('userData', root);
  process.env.CATNIP_PROJECTS_ROOT = path.join(root, 'projects');
  process.env.CATNIP_PROJECT_SESSIONS_ROOT = path.join(root, 'sessions');
  for (const name of ['alpha', 'beta']) fs.mkdirSync(path.join(process.env.CATNIP_PROJECTS_ROOT, name), { recursive: true });
  await app.whenReady();
  const { ChatBuffer } = require('../dist/main/worker/chat-buffer');
  const { Orchestrator } = require('../dist/main/worker/orchestrator');
  const { activateProject, getProjectSessionStatus } = require('../dist/main/project-session');
  const store = require('../dist/main/worker/session-store');
  const { upsertChatMessage, mergeAssistantResponse, normalizeResponseStreamId, ASSISTANT_RESPONSE_LIMIT, ASSISTANT_RESPONSE_SUFFIX } = require('../dist/common/chat-stream');
  const projects = getProjectSessionStatus().projects;
  activateProject(projects.find(p => p.name === 'alpha').id);
  const conversationId = store.listChatConversations().activeConversationId;
  let displayed = [];
  const received = [];
  const worker = Object.create(Orchestrator.prototype);
  Object.assign(worker, { currentTaskId: 'task-a', currentExecutionProfile: 'default', currentAgentTranscript: '', transcriptResponseId: null, queuedTasks: [], pendingGuidance: [], state: { advanceTo() {} }, pushUI: (channel, data) => {
    if (channel !== 'chat:message') return;
    const message = store.appendChatMessage(conversationId, { ...data, id: data.id || `event-${received.length}`, role: 'agent' });
    received.push(message);
    displayed = upsertChatMessage(displayed, message);
  } });
  const fragments = ['时钟在', '走：00:01:00 → 00:02:00；\n\n| 现象 | 调整 |\n| --- | --- |\n| 背光', '亮但全黑 | 初始化 ', '|\n| 颜色偏 | 字节序 |\n\n```c\n', '  return 0;', '\n```\n', ' '];
  const buffer = new ChatBuffer();
  for (const text of fragments) {
    const wire = JSON.stringify({ type: 'assistant', message: { content: [{ type: 'text', id: 'rig-text-1', text }] } }) + '\n';
    assert.equal(buffer.feed(wire.slice(0, 7)).length, 0);
    const chunks = buffer.feed(wire.slice(7));
    assert.equal(chunks[0].textId, 'rig-text-1');
    worker.handleParsedChunk(chunks[0]);
  }
  const expected = fragments.join('');
  assert.equal(displayed.length, 1, 'stream deltas must update one Agent bubble');
  assert.equal(displayed[0].text, expected);
  assert.equal(displayed[0].timestamp, received[0].timestamp);
  assert.equal(worker.currentAgentTranscript, expected, 'turn summary must preserve exact fragment joins');
  assert.equal(store.getChatConversation(conversationId).messages.length, 1);
  assert.equal(store.getChatConversation(conversationId).messages[0].text, expected, 'reload must preserve whitespace, tables and code indentation');
  const source = fs.readFileSync(path.join(__dirname, '../src/renderer/components/MarkdownContent.tsx'), 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React, esModuleInterop: true } }).outputText;
  const output = { exports: {} }; new Function('require', 'module', 'exports', compiled)(require, output, output.exports);
  const html = renderToStaticMarkup(React.createElement(output.exports.default, { text: displayed[0].text }));
  assert.match(html, /时钟在走：00:01:00/); assert.match(html, /<table>/);
  assert.equal((html.match(/<tbody>/g) || []).length, 1); assert.match(html, /<td>背光亮但全黑<\/td>/);
  assert.match(html, /<code data-language="c">  return 0;/);
  worker.handleParsedChunk({ type: 'tool_call', toolName: 'Read', content: 'read', toolInput: {} });
  worker.handleParsedChunk({ type: 'tool_result', content: 'result' });
  worker.handleParsedChunk({ type: 'text', textId: 'rig-text-2', content: '另一次模型回复' });
  worker.handleParsedChunk({ type: 'thinking', thinkingId: 'rig-think-2', content: '供应商思考' });
  assert.equal(displayed.filter(m => m.streamId).length, 2);
  assert.equal(displayed[0].text, expected);
  assert.equal(displayed.filter(m => m.kind === 'detail').length, 2);
  assert(!worker.currentAgentTranscript.includes('供应商思考'));
  worker.currentTaskId = 'task-b'; worker.transcriptResponseId = null;
  worker.handleParsedChunk({ type: 'text', textId: 'rig-text-1', content: '新任务' });
  assert.equal(displayed.filter(m => m.streamId).length, 3, 'request IDs must be scoped by task');
  assert.equal(normalizeResponseStreamId('untrusted-id'), undefined);
  const clipped = mergeAssistantResponse('a'.repeat(ASSISTANT_RESPONSE_LIMIT - 1), '😀'.repeat(100));
  assert(clipped.length <= ASSISTANT_RESPONSE_LIMIT); assert(clipped.endsWith(ASSISTANT_RESPONSE_SUFFIX));
  assert.equal(mergeAssistantResponse(clipped, 'more'), clipped);
  const long = store.appendChatMessage(conversationId, { id: 'long', text: '中文'.repeat(15000), role: 'agent', kind: 'conversation', taskId: 'long-task', streamId: 'rig-text-9', timestamp: 1 });
  assert.equal(store.getChatConversation(conversationId).messages.find(m => m.id === 'long').text.length, 30000, 'normal long answers must exceed the old 20k per-fragment display limit');
  const another = store.createChatConversation('独立对话');
  store.appendChatMessage(another.id, { ...long, text: '独立内容' });
  assert.equal(store.getChatConversation(conversationId).messages.find(m => m.id === 'long').text.length, 30000);
  activateProject(projects.find(p => p.name === 'beta').id);
  assert.equal(store.getChatConversation().messages.length, 0);
  activateProject(projects.find(p => p.name === 'alpha').id);
  assert.equal(store.getChatConversation(conversationId).messages[0].text, expected);
  console.log('Chat stream passed: one bubble per response, split Unicode/whitespace/Markdown intact, no duplicate Renderer append, exact transcript, bounded long answers, Tool/thinking/task/conversation/project isolation and reload.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { fs.rmSync(root, { recursive: true, force: true }); app.quit(); });
